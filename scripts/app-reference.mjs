import { readFile, writeFile } from "node:fs/promises";

const source = "https://horizon.pm/v3/api-docs/app";
const snapshotFile = new URL("../src/resources/api/app-openapi.json", import.meta.url);
const referenceFile = new URL("../src/resources/api/app-api.md", import.meta.url);
const methods = ["get", "post", "put", "patch", "delete", "head", "options", "trace"];
const guideNames = {
  "crash-reports": "crash-reporting",
  leaderboards: "leaderboard",
  "user-feedback": "feedback",
  "user-management": "auth",
};

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value === null || typeof value !== "object") return value;
  return Object.fromEntries(Object.keys(value).sort().map(key => [key, sortKeys(value[key])]));
}

function snapshot(spec) {
  if (!/^3\./.test(spec?.openapi) || !Object.keys(spec.paths ?? {}).length) {
    throw new Error("Expected a nonempty OpenAPI 3 App API document.");
  }
  // Spring discovers tags in controller-registration order. That order is not part of the API.
  const tags = [...(spec.tags ?? [])].sort((a, b) => a.name.localeCompare(b.name));
  return JSON.stringify(sortKeys({ ...spec, tags }), null, 2) + "\n";
}

function operationsByFamily(spec) {
  const groups = new Map();
  for (const [path, pathItem] of Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b))) {
    const match = /^\/api\/v1\/app\/([a-z][a-z0-9-]*)(?:\/|$)/.exec(path);
    if (!match) throw new Error(`Unexpected path in the App API specification: ${path}`);
    const family = match[1];
    const operations = methods.filter(method => pathItem[method]);
    if (!operations.length) throw new Error(`No HTTP operations found for ${path}`);
    const group = groups.get(family) ?? [];
    for (const method of operations) {
      group.push({ method: method.toUpperCase(), path, operation: pathItem[method] });
    }
    groups.set(family, group);
  }
  return groups;
}

function render(spec) {
  const groups = operationsByFamily(spec);
  const count = [...groups.values()].reduce((total, operations) => total + operations.length, 0);
  const lines = [
    "<!-- Generated by npm run docs:update. Edit the server's OpenAPI contract at the source. -->",
    "# horizOn App API reference",
    "",
    `${count} HTTP operations from the [hosted App OpenAPI](${source}).`,
    "Read the OpenAPI resource for the relevant section to see parameters, payload schemas, responses and security definitions.",
    "The linked guides describe session requirements, setup, SDK usage and workflows such as WebSocket subscriptions.",
    "For Dashboard operations and key scopes, read <horizon://docs/dashboard>. For current quotas, read <horizon://docs/limits>.",
  ];
  for (const [family, operations] of groups) {
    const guide = guideNames[family] ?? family;
    lines.push("", `## ${family}`, "", `OpenAPI <horizon://api/openapi/${family}> · Guide <horizon://docs/${guide}>`, "");
    for (const { method, path, operation } of operations) {
      const summary = operation.summary?.replace(/\s+/g, " ").trim();
      lines.push(`- \`${method} ${path}\`${summary ? ` — ${summary}` : ""}`);
    }
  }
  return lines.join("\n") + "\n";
}

async function fetchLiveSpec() {
  const response = await fetch(source, { signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw new Error(`Could not read ${source} (HTTP ${response.status}).`);
  return response.json();
}

async function main() {
  const command = process.argv[2];
  if (command === "update") {
    const spec = await fetchLiveSpec();
    const json = snapshot(spec);
    const markdown = render(spec);
    await Promise.all([writeFile(snapshotFile, json), writeFile(referenceFile, markdown)]);
    return;
  }
  if (command !== "check" && command !== "check-live") {
    throw new Error("Usage: node scripts/app-reference.mjs update|check|check-live");
  }

  const [savedSpec, savedReference] = await Promise.all([
    readFile(snapshotFile, "utf8"), readFile(referenceFile, "utf8"),
  ]);
  if (render(JSON.parse(savedSpec)) !== savedReference) {
    throw new Error("The bundled API reference does not match its OpenAPI snapshot. Run npm run docs:update.");
  }
  if (command === "check-live" && snapshot(await fetchLiveSpec()) !== savedSpec) {
    throw new Error("The hosted App OpenAPI has changed. Run npm run docs:update and review the API and guide changes before releasing.");
  }
  console.log("App API reference matches " + (command === "check-live" ? "the hosted OpenAPI." : "the bundled OpenAPI snapshot."));
}

main().catch(error => {
  console.error(error.message);
  process.exitCode = 1;
});
